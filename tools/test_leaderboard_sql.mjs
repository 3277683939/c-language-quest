  assert.equal(rows.length,1);
  assert.equal(rows[0].mine,false);
  assert.ok(!JSON.stringify(rows).includes(alice) && !JSON.stringify(rows).includes('PRIVATE_DRAFT'));
  console.log('PASS: exact IDs, opt-in privacy, verified membership, nickname validation, RLS, unique solved counts, ties, withdrawal and private data isolation');
