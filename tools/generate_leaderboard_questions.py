"""Generate the exact server-side choice ID allowlist; no user data or credentials."""
import collections
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    text = (ROOT / 'overrides/bank.js').read_text(encoding='utf-8-sig')
    data, _ = json.JSONDecoder().raw_decode(text[text.index('{'):])
    groups = collections.defaultdict(list)
    ids = [q['id'] for q in data['questions']]
    if len(ids) != len(set(ids)):
        raise ValueError('Duplicate IDs')
    for qid in ids:
        prefix, number = qid.rsplit('-', 1)
        groups[prefix + '-'].append(int(number))
    values = []
    for prefix, numbers in sorted(groups.items()):
        low, high = min(numbers), max(numbers)
        missing = sorted(set(range(low, high + 1)) - set(numbers))
        if high - low > len(numbers) * 3:
            # Sparse scan question numbers: exact list, no giant generated range.
            expression = 'ARRAY[' + ','.join(map(str, sorted(numbers))) + ']'
        else:
            expression = f'ARRAY(select n from generate_series({low},{high}) n'
            if missing:
                expression += ' where n not in (' + ','.join(map(str, missing)) + ')'
            expression += ')'
        values.append("('" + prefix.replace("'", "''") + "'," + expression + ')')
    sql = '''-- Generated by tools/generate_leaderboard_questions.py; rerun after adding choices.
begin;
create table if not exists public.cquest_rank_questions(id text primary key, active boolean not null default true);
alter table public.cquest_rank_questions enable row level security;
alter table public.cquest_rank_questions force row level security;
revoke all on public.cquest_rank_questions from public,anon,authenticated;
update public.cquest_rank_questions set active=false;
insert into public.cquest_rank_questions(id,active)
select prefix || n::text,true from (values
''' + ',\n'.join(values) + ''') as groups(prefix,numbers)
cross join lateral unnest(numbers) n
on conflict(id) do update set active=true;
commit;
'''
    (ROOT / 'cloud/leaderboard-questions.sql').write_text(sql, encoding='utf-8', newline='\n')
    print(f'Generated exact {len(ids)}-question allowlist')


if __name__ == '__main__':
    generate()
